#!/usr/bin/env python3
"""Build TipOfDay/fr/tod.xml for xLights Cloud.

The French tips window reads TipOfDay/fr/tod.xml from the xlights-cloud
branch on GitHub. It lists every official tip, in the official order:
  - a tip translated in TipOfDay/fr/ is listed by its file name;
  - any other tip points at the official English page, so new tips from the
    xLights team still show (in English) until they are translated.

  python ci_scripts/xlights_cloud_tips.py [official-tod.xml]

Without an argument the official list is TipOfDay/tod.xml of this checkout.
"""

import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FR_DIR = os.path.join(ROOT, "TipOfDay", "fr")
OFFICIAL_URL = "https://raw.githubusercontent.com/xLightsSequencer/xLights/master/TipOfDay/"


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "TipOfDay", "tod.xml")
    tips = ET.parse(source).getroot().findall("tip")

    out = ET.Element("tipofday")
    translated = 0
    for tip in tips:
        url = tip.get("url", "")
        if not url:
            continue
        entry = ET.SubElement(out, "tip", dict(tip.attrib))
        if os.path.isfile(os.path.join(FR_DIR, url)):
            translated += 1
        else:
            entry.set("url", OFFICIAL_URL + url)

    ET.indent(out, space="   ")
    os.makedirs(FR_DIR, exist_ok=True)
    with open(os.path.join(FR_DIR, "tod.xml"), "w", encoding="utf-8", newline="\n") as f:
        f.write("<!-- Generated by ci_scripts/xlights_cloud_tips.py ... do not edit -->\n")
        f.write(ET.tostring(out, encoding="unicode"))
        f.write("\n")
    print(f"French tips: {translated} of {len(tips)} translated")


if __name__ == "__main__":
    main()
